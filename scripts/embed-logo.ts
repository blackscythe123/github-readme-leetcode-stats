// Regenerates src/logo.ts from assets/leetcode-64.png + assets/leetcode-64-white.png.
// Run after replacing the logo assets: npx tsx scripts/embed-logo.ts
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const uri = (file: string) =>
  `data:image/png;base64,${readFileSync(resolve(root, "assets", file)).toString("base64")}`;

const out = `// GENERATED by scripts/embed-logo.ts — do not edit by hand.
// Official LeetCode logo inlined as data URIs so the card renders through
// GitHub's camo proxy, which blocks external image fetches.
// ON_LIGHT: original asset (black bracket) — for light/mid backgrounds.
// ON_DARK: white-bracket variant — for dark backgrounds where black would vanish.
export const LOGO_ON_LIGHT =
  "${uri("leetcode-64.png")}";
export const LOGO_ON_DARK =
  "${uri("leetcode-64-white.png")}";
`;
writeFileSync(resolve(root, "src/logo.ts"), out);
console.log(`src/logo.ts written (${out.length} chars)`);
