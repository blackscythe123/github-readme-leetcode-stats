// Regenerates src/logo.ts from assets/leetcode-64.png.
// Run after replacing the logo asset: npx tsx scripts/embed-logo.ts
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const png = readFileSync(resolve(root, "assets/leetcode-64.png"));
const dataUri = `data:image/png;base64,${png.toString("base64")}`;

const out = `// GENERATED by scripts/embed-logo.ts — do not edit by hand.
// Official LeetCode logo (assets/leetcode-64.png) inlined as a data URI so the
// card renders through GitHub's camo proxy, which blocks external image fetches.
export const LOGO_DATA_URI =
  "${dataUri}";
`;
writeFileSync(resolve(root, "src/logo.ts"), out);
console.log(`src/logo.ts written (${dataUri.length} chars)`);
