// Theme resolution: name -> base ThemeColors (from themes.json) + per-key overrides + hide_border.
//
// NOTE on the `transparent` query param (background -> "#0000" on ANY theme): that is applied
// entirely in params.ts, which forces `colorOverrides.background = "#0000"` whenever
// `transparent=true` (winning over any `background=` override too — see params.ts). resolveTheme
// here needs no special-casing for it: colorOverrides always wins over the base theme's
// background because of the plain object-spread merge below, so a forced "#0000" override
// flows through unchanged. This keeps theme.ts a pure "name + overrides -> colors" resolver.

import type { ThemeColors } from "./types";

// themes.json is generated by scripts/port-themes.ts (may land in parallel with this file).
// Structure: a flat map of kebab-case theme name -> ThemeColors, always including "default".
import themesData from "./themes.json";

const themes = themesData as unknown as Record<string, ThemeColors>;

/** All known theme names, as they appear as keys in themes.json. */
export function themeNames(): string[] {
  return Object.keys(themes);
}

function normalizeThemeName(name: string): string {
  return (name ?? "").trim().toLowerCase().replace(/_/g, "-");
}

/**
 * Resolve a theme name (already normalized by params.ts, but normalized again here
 * defensively since resolveTheme is a public contract function other callers may use
 * directly) to a full ThemeColors, applying per-key overrides and hide_border.
 * Unknown theme names fall back to "default".
 */
export function resolveTheme(
  name: string,
  overrides: Partial<ThemeColors>,
  hideBorder: boolean,
): ThemeColors {
  const normalized = normalizeThemeName(name);
  const base = Object.prototype.hasOwnProperty.call(themes, normalized)
    ? themes[normalized]
    : themes["default"];

  if (!base) {
    throw new Error(
      "theme.ts: themes.json is missing a 'default' theme entry — cannot resolve any theme.",
    );
  }

  const resolved: ThemeColors = { ...base, ...overrides };

  if (hideBorder) {
    resolved.border = "#0000";
  }

  return resolved;
}
